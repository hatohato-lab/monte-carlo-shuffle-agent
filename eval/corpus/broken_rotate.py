# 陰性対照: 巡回シフト。呼ばれるたびに 1 つずつ回して返すだけ。
# 呼び出しを重ねると各要素はどの位置にも均等に現れるため、
# 「位置ごとの周辺分布」のカイ二乗検定は通ってしまう（χ²≈0）。
# しかし出せる並びは len(xs) 通りしかない（4要素なら 24 通り中 4 通り）ので、
# 順列全体のカイ二乗検定で FAIL する。周辺分布検定だけでは足りないことの実証。
_calls = 0


def shuffle(xs):
    global _calls
    _calls += 1
    ys = list(xs)
    if ys:
        k = _calls % len(ys)
        ys = ys[k:] + ys[:k]
    return ys
